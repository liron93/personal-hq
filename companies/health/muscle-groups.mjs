const norm = s => String(s ?? "").toLowerCase().trim();

/** קבוצת השריר של תרגיל, לפי התאמת מילת-מפתח ראשונה (לא רגיש לרישיות/שפה). null אם
    שום מילת מפתח לא תאמה - "לא ממופה", לא "אחר" מומצא. */
export function detectMuscleGroup(name, dict = DEFAULT_MUSCLE_DICT) {
  const n = norm(name);
  if (!n) return null;
  for (const [keyword, group] of Object.entries(dict || {})) {
    if (keyword && n.includes(norm(keyword))) return group;
  }
  return null;
}

/** הוספת/עריכת מילת מפתח במילון (רק לקבוצה תקנית מ-MUSCLE_GROUPS). */
export function addMuscleKeyword(dict, keyword, group) {
  const k = norm(keyword);
  if (!k || !MUSCLE_GROUPS.includes(group)) return dict;
  return { ...dict, [k]: group };
}
